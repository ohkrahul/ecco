import { chromium } from 'playwright-core';
const out = process.argv[2];
const b = await chromium.launch({ channel: 'msedge' });
const page = await b.newPage({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true });
await page.goto('http://localhost:5173/');
await page.waitForTimeout(2000);
await page.screenshot({ path: `${out}/m-load.png` });
await page.waitForSelector('#preloader.is-leaving', { timeout: 15000 });
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/m-scan.png` });
await page.waitForSelector('html.is-ready');
await page.waitForTimeout(1500);
await page.click('.menu-btn');
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/m-menu.png` });
await page.click('.nav a[href="#zone"]');
await page.waitForTimeout(4500);
await page.screenshot({ path: `${out}/m-zone.png` });
